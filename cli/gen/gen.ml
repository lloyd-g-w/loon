open! Core
open Loon_scan

(* A quoted string literal for [s]: {loon|...|loon}, with a delimiter [s]
   does not contain. *)
let quote s =
  let rec delimiter i =
    let id = if i = 0 then "loon" else sprintf "loon%d" i in
    if String.is_substring s ~substring:("|" ^ id ^ "}")
    then delimiter (i + 1)
    else id
  in
  let id = delimiter 0 in
  sprintf "{%s|%s|%s}" id s id
;;

let file (f : Entry.File.t) =
  sprintf "{ File.name = %S; contents = %s }" f.name (quote f.contents)
;;

let list xs = "[ " ^ String.concat ~sep:"\n    ; " xs ^ " ]"

let () =
  match Sys.get_argv () |> Array.to_list with
  | _ :: dune_file :: files ->
    let read path = In_channel.read_all path in
    let files =
      List.filter files ~f:(fun p -> not (String.equal p dune_file))
      |> List.map ~f:(fun p -> p, read p)
    in
    let generated = Entry.generated_modules (read dune_file) in
    let entries = Entry.build files ~generated in
    print_string
      "(* Generated by cli/gen from loon's src/. *)\nopen Loon_scan.Entry\n\n";
    print_string "let all =\n  [ ";
    print_string
      (String.concat
         ~sep:"\n  ; "
         (List.map entries ~f:(fun (e : Entry.t) ->
            sprintf
              "{ name = %S\n\
              \    ; description = %S\n\
              \    ; sources =\n\
              \    %s\n\
              \    ; css =\n\
              \    %s\n\
              \    ; deps = %s\n\
              \    }"
              e.name
              e.description
              (list (List.map e.sources ~f:file))
              (list (List.map e.css ~f:file))
              (list (List.map e.deps ~f:(sprintf "%S"))))));
    print_string "\n  ]\n"
  | _ -> failwith "usage: gen DUNE_FILE FILE..."
;;
