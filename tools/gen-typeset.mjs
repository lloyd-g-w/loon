// node tools/gen-typeset.mjs [SHADCN]: writes the docs' Typeset page's data
// from shadcn/ui's checkout (default ~/src/shadcn-ui):
//   docs/lib/typeset/typeset_fixtures.ml  the previewed documents (lib/fixtures)
//   docs/lib/typeset/typeset_css.ml       typeset.css as it is, to copy
//   docs/lib/typeset/typeset.css          typeset.css for the docs' Tailwind
//     input: the same rules, sized by the preview's width (a container
//     query) rather than the window's, as shadcn's preview is an iframe.
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const shadcn = process.argv[2] ?? join(homedir(), "src/shadcn-ui");
const dir = join(shadcn, "apps/v4/app/(app)/(typeset)");
const out = new URL("../docs/lib/typeset/", import.meta.url).pathname;

const quote = (s) => {
  if (s.includes("|t}")) throw new Error("text contains |t}");
  return `{t|${s}|t}`;
};

// The template literal [export const NAME = `...`] or string ["..."].
const constant = (file, name) => {
  const src = readFileSync(join(dir, "lib/fixtures", file), "utf8");
  const tpl = src.match(new RegExp(`export const ${name} =\\s*\`([^\`]*)\``));
  if (tpl) {
    if (tpl[1].includes("${") || tpl[1].includes("\\")) throw new Error(`${name}: escapes`);
    return tpl[1];
  }
  const str = src.match(new RegExp(`export const ${name} =\\s*"((?:[^"\\\\]|\\\\.)*)"`));
  if (str) return JSON.parse(`"${str[1]}"`);
  throw new Error(`${name} not found in ${file}`);
};

const fixtures = [
  ["docs", "docs.ts", "DOCS_HTML"],
  ["chat", "chat.ts", "CHAT_HTML"],
  ["article", "article.ts", "ARTICLE_HTML"],
  ["changelog", "changelog.ts", "CHANGELOG_HTML"],
  ["notes", "notes.ts", "NOTES_HTML"],
  ["recipe", "recipe.ts", "RECIPE_HTML"],
  ["elements", "elements.ts", "KITCHEN_SINK_HTML"],
  ["tailwind", "tailwind.ts", "TAILWIND_HTML"],
];

const header = "(* Generated by tools/gen-typeset.mjs from shadcn/ui's (typeset): do not edit. *)\n\n";
let ml = header;
ml += `let chat_question = ${quote(constant("chat.ts", "CHAT_QUESTION"))}\n\n`;
ml += "let all =\n  [ ";
ml += fixtures
  .map(([value, file, name]) => `${JSON.stringify(value)}, ${quote(constant(file, name))}`)
  .join("\n  ; ");
ml += "\n  ]\n;;\n";
writeFileSync(join(out, "typeset_fixtures.ml"), ml);

const css = readFileSync(join(dir, "typeset.css"), "utf8");
writeFileSync(join(out, "typeset_css.ml"), `${header}let css = ${quote(css)}\n`);

const media = "@media (min-width: 48rem), print {";
if (!css.includes(media)) throw new Error("typeset.css: its breakpoint changed");
// typeset/layout.tsx's PARAMS_STYLE, with its defaults.
const params = `
/* typeset/layout.tsx's PARAMS_STYLE. */
.preview-params .typeset {
  --typeset-leading: var(--preview-leading, 1.75);
  --typeset-flow: var(--preview-flow, 1.25em);
}

/* ui.shadcn.com's globals.css utilities the customisers use. */
@utility no-scrollbar {
  -ms-overflow-style: none;
  scrollbar-width: none;

  &::-webkit-scrollbar {
    display: none;
  }
}
`;
writeFileSync(
  join(out, "typeset.css"),
  "/* Generated by tools/gen-typeset.mjs: shadcn/ui's typeset.css, its breakpoint\n" +
    "   the preview's width (container typeset-preview), not the window's. */\n\n" +
    css.replace(media, "@container typeset-preview (min-width: 48rem) {") +
    params,
);
console.log(`${fixtures.length} fixtures, typeset.css ${css.length} bytes`);
