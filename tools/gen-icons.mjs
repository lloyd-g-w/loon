// nix run .#gen-icons: writes src/icon.ml(i), the Lucide icons
// (https://lucide.dev, ISC licence) named in tools/icons.txt, and
// src/tabler.ml(i), the Tabler icons (https://tabler.io/icons, MIT) named in
// tools/tabler-icons.txt, as the npm packages shadcn/ui pins draw them
// (lucide-react, @tabler/icons-react: tools/icons.nix fetches them and sets
// $LUCIDE_REACT and $TABLER_ICONS_REACT to their directories).
//
// Lucide names may be file names ("circle-check"), lucide-react names
// ("CheckCircle2Icon") or its aliases; Tabler names are @tabler/icons-react's
// ("IconDots", "IconCircleCheckFilled") or its file names ("dots",
// "circle-check-filled"). Add the ones a port needs and run this again.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const env = (v) => {
  if (!process.env[v]) {
    console.error(`gen-icons: $${v} is not set (run \`nix run .#gen-icons\`)`);
    process.exit(1);
  }
  return process.env[v];
};
const lucideDir = join(env("LUCIDE_REACT"), "dist/esm");
const tablerDir = join(env("TABLER_ICONS_REACT"), "dist/esm");

const wantedIn = (file) =>
  readFileSync(join(root, "tools", file), "utf8")
    .split("\n")
    .map((l) => l.replace(/#.*/, "").trim())
    .filter(Boolean);

// The icon's node list, as the package's module defines it
// (`const __iconNode = [["path", { d: "...", key: "..." }], ...];`), without
// React's keys.
const iconNode = (js, file) => {
  const m = js.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!m) throw new Error(`no __iconNode in ${file}`);
  return new Function(`return ${m[1]}`)().map(([tag, attrs]) => [
    tag,
    Object.entries(attrs).filter(([k]) => k !== "key"),
  ]);
};

const constructor = (n) => {
  const c = n.charAt(0).toUpperCase() + n.slice(1).replaceAll("-", "_");
  return /^[0-9]/.test(c) ? "I" + c : c;
};

const resolve = (byName, wanted, what) => {
  const missing = wanted.filter((w) => !byName.has(w));
  if (missing.length) {
    console.error(`unknown ${what} icons:`, missing.join(" "));
    process.exit(1);
  }
  return [...new Set(wanted.map((w) => byName.get(w)))].sort();
};

const q = JSON.stringify; // OCaml accepts JSON's escapes for these strings

// icons: [{ name, className, filled?, node }]; svgAttrs: OCaml for the
// <svg>'s attributes, before the caller's.
const writeModule = ({ file, header, mliDoc, icons, viewDoc, svgAttrs }) => {
  const ml = [];
  ml.push(`(* Generated by tools/gen-icons.mjs from ${header}; do not edit. *)`);
  ml.push("open! Import\n");
  ml.push("type t =");
  for (const i of icons) ml.push(`  | ${constructor(i.name)}`);
  ml.push("[@@deriving enumerate, sexp_of, compare, equal]\n");
  ml.push("let name = function");
  for (const i of icons) ml.push(`  | ${constructor(i.name)} -> ${q(i.name)}`);
  ml.push(";;\n");
  ml.push("let of_name = function");
  for (const i of icons) ml.push(`  | ${q(i.name)} -> Some ${constructor(i.name)}`);
  ml.push("  | _ -> None\n;;\n");
  ml.push("let class_name = function");
  for (const i of icons) ml.push(`  | ${constructor(i.name)} -> ${q(i.className)}`);
  ml.push(";;\n");
  if (icons.some((i) => i.filled !== undefined)) {
    ml.push("let filled = function");
    for (const i of icons) ml.push(`  | ${constructor(i.name)} -> ${i.filled}`);
    ml.push(";;\n");
  }
  ml.push("let shapes = function");
  for (const i of icons) {
    const s = i.node
      .map(([tag, attrs]) => `(${q(tag)}, [ ${attrs.map(([k, v]) => `${q(k)}, ${q(String(v))}`).join("; ")} ])`)
      .join("; ");
    ml.push(`  | ${constructor(i.name)} -> [ ${s} ]`);
  }
  ml.push(";;\n");
  ml.push(`let view ?(attrs = []) ?class_ ?(stroke_width = "2") t =
  Node.create_svg
    "svg"
    ~attrs:
      (${svgAttrs}
       @ attrs)
    (List.map (shapes t) ~f:(fun (tag, shape_attrs) ->
       Node.create_svg
         tag
         ~attrs:(List.map shape_attrs ~f:(fun (k, v) -> Attr.create k v))
         []))
;;`);
  writeFileSync(join(root, `src/${file}.ml`), ml.join("\n") + "\n");

  const mli = [];
  mli.push(mliDoc + "\n");
  mli.push("open! Import\n");
  mli.push("type t =");
  for (const i of icons) mli.push(`  | ${constructor(i.name)}`);
  mli.push("[@@deriving enumerate, sexp_of, compare, equal]\n");
  mli.push(`(** Its file name in the package: [${icons[0].name}]. *)`);
  mli.push("val name : t -> string\n");
  mli.push("val of_name : string -> t option\n");
  mli.push(viewDoc);
  mli.push("val view : ?attrs:Attr.t list -> ?class_:string -> ?stroke_width:string -> t -> Node.t");
  writeFileSync(join(root, `src/${file}.mli`), mli.join("\n") + "\n");
  console.log(`src/${file}.ml: ${icons.length} icons`);
};

// Lucide: dist/esm/icons/NAME.js defines the icon
// (`createLucideIcon("Trash2", __iconNode)`); dist/esm/lucide-react.js
// exports it under each of its names.
{
  const pascal = (kebab) =>
    kebab.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
  const byName = new Map();
  const aliases = []; // [alias file, the icon's file] (`export { default } from './x.js'`)
  for (const f of readdirSync(join(lucideDir, "icons"))) {
    if (!f.endsWith(".js") || f === "index.js") continue;
    const name = f.slice(0, -3);
    const alias = readFileSync(join(lucideDir, "icons", f), "utf8").match(/^export \{ default \} from '\.\/([\w-]+)\.js';$/m);
    if (alias) aliases.push([name, alias[1]]);
    else for (const s of [name, pascal(name), pascal(name) + "Icon", "Lucide" + pascal(name)]) byName.set(s, name);
  }
  for (const [alias, name] of aliases)
    for (const s of [alias, pascal(alias), pascal(alias) + "Icon", "Lucide" + pascal(alias)])
      if (!byName.has(s)) byName.set(s, name);
  const index = readFileSync(join(lucideDir, "lucide-react.js"), "utf8");
  for (const m of index.matchAll(/^export \{ (.*) \} from '\.\/icons\/([\w-]+)\.js';$/gm)) {
    for (const a of m[1].matchAll(/default as (\w+)/g)) if (!byName.has(a[1])) byName.set(a[1], m[2]);
  }
  // lucide-react's class: lucide-${toKebabCase(iconName)} ("Trash2" -> "trash2").
  const toKebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
  const icons = resolve(byName, wantedIn("icons.txt"), "Lucide").map((name) => {
    const file = join(lucideDir, "icons", name + ".js");
    const js = readFileSync(file, "utf8");
    const iconName = js.match(/createLucideIcon\("(\w+)", __iconNode\)/)[1];
    return { name, className: "lucide-" + toKebab(iconName), node: iconNode(js, file) };
  });
  writeModule({
    file: "icon",
    header: "lucide-react 0.474.0 (ISC licence)",
    icons,
    mliDoc: `(** Lucide icons (https://lucide.dev, ISC licence), drawn as lucide-react
    0.474.0 (the version shadcn/ui uses) draws them: a 24x24 [<svg>] stroked
    with [currentColor], classes [lucide lucide-NAME]. shadcn/ui's components
    size them with their [[&_svg]:size-4] classes. Generated by
    tools/gen-icons.mjs: the icons are those in tools/icons.txt. *)`,
    viewDoc: `(** The icon. [class_] goes after [lucide lucide-NAME] (e.g. [size-4
    text-muted-foreground]); [stroke_width] is ["2"]. *)`,
    svgAttrs: `[ Attr.create "xmlns" "http://www.w3.org/2000/svg"
       ; Attr.create "width" "24"
       ; Attr.create "height" "24"
       ; Attr.create "viewBox" "0 0 24 24"
       ; Attr.create "fill" "none"
       ; Attr.create "stroke" "currentColor"
       ; Attr.create "stroke-width" stroke_width
       ; Attr.create "stroke-linecap" "round"
       ; Attr.create "stroke-linejoin" "round"
       ; Attr.classes ([ "lucide"; class_name t ] @ Option.to_list class_)
       ]`,
  });
}

// Tabler: dist/esm/icons/IconNAME.mjs defines the icon
// (`createReactComponent("outline", "dots", "Dots", __iconNode)`).
{
  const byName = new Map();
  const defs = new Map();
  for (const f of readdirSync(join(tablerDir, "icons"))) {
    const m = f.match(/^Icon(\w+)\.mjs$/);
    if (!m) continue;
    const file = join(tablerDir, "icons", f);
    const js = readFileSync(file, "utf8");
    const [, type, name] = js.match(/createReactComponent\("(\w+)", "([\w-]+)", "\w+", __iconNode\)/);
    defs.set(name, { file, js, type });
    for (const s of [name, "Icon" + m[1], m[1]]) if (!byName.has(s)) byName.set(s, name);
  }
  const icons = resolve(byName, wantedIn("tabler-icons.txt"), "Tabler").map((name) => {
    const { file, js, type } = defs.get(name);
    return { name, className: "tabler-icon-" + name, filled: type === "filled", node: iconNode(js, file) };
  });
  writeModule({
    file: "tabler",
    header: "@tabler/icons-react 3.34.1 (MIT licence)",
    icons,
    mliDoc: `(** Tabler icons (https://tabler.io/icons, MIT licence), drawn as
    @tabler/icons-react 3.34.1 (the version shadcn/ui's blocks use) draws
    them: a 24x24 [<svg>], stroked with [currentColor] (filled with it for
    the [*_filled] icons), classes [tabler-icon tabler-icon-NAME]. Generated
    by tools/gen-icons.mjs: the icons are those in tools/tabler-icons.txt. *)`,
    viewDoc: `(** The icon. [class_] goes after [tabler-icon tabler-icon-NAME];
    [stroke_width] (["2"]) is for the outline icons. *)`,
    svgAttrs: `(if filled t
        then
          [ Attr.create "xmlns" "http://www.w3.org/2000/svg"
          ; Attr.create "width" "24"
          ; Attr.create "height" "24"
          ; Attr.create "viewBox" "0 0 24 24"
          ; Attr.create "fill" "currentColor"
          ; Attr.create "stroke" "none"
          ]
        else
          [ Attr.create "xmlns" "http://www.w3.org/2000/svg"
          ; Attr.create "width" "24"
          ; Attr.create "height" "24"
          ; Attr.create "viewBox" "0 0 24 24"
          ; Attr.create "fill" "none"
          ; Attr.create "stroke" "currentColor"
          ; Attr.create "stroke-width" stroke_width
          ; Attr.create "stroke-linecap" "round"
          ; Attr.create "stroke-linejoin" "round"
          ])
       @ [ Attr.classes ([ "tabler-icon"; class_name t ] @ Option.to_list class_) ]`,
  });
}
