// node tools/gen-icons.mjs: writes src/icon.ml and src/icon.mli, the Lucide
// icons (https://lucide.dev, ISC licence) named in tools/icons.txt, from a
// checkout of github.com/lucide-icons/lucide ($LUCIDE_DIR, default
// ~/src/lucide). Names may be kebab-case file names ("circle-check"),
// lucide-react names ("CheckCircle2Icon") or aliases ("home"); add the ones
// a port needs to tools/icons.txt and run this again.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const lucide = process.env.LUCIDE_DIR ?? join(homedir(), "src/lucide");
const iconsDir = join(lucide, "icons");

// lucide-react's PascalCase for a kebab name: "trash-2" -> "Trash2".
const pascal = (kebab) =>
  kebab.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");

// Icons Lucide no longer ships (its brand icons, as lucide-react 0.x drew
// them), in tools/extra-icons/NAME.svg.
const extraDir = join(root, "tools/extra-icons");
const extras = new Set(readdirSync(extraDir).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)));
const svgPath = (name) => join(extras.has(name) ? extraDir : iconsDir, name + ".svg");

const byName = new Map(); // any accepted spelling -> canonical file name
for (const name of extras) for (const s of [name, pascal(name), pascal(name) + "Icon"]) byName.set(s, name);
for (const f of readdirSync(iconsDir)) {
  if (!f.endsWith(".json")) continue;
  const name = f.slice(0, -5);
  const meta = JSON.parse(readFileSync(join(iconsDir, f), "utf8"));
  const names = [name, ...(meta.aliases ?? []).map((a) => (typeof a === "string" ? a : a.name))];
  for (const n of names) {
    for (const spelling of [n, pascal(n), pascal(n) + "Icon", "Lucide" + pascal(n)]) {
      if (!byName.has(spelling)) byName.set(spelling, name);
    }
  }
}

const wanted = readFileSync(join(root, "tools/icons.txt"), "utf8")
  .split("\n")
  .map((l) => l.replace(/#.*/, "").trim())
  .filter(Boolean);
const missing = wanted.filter((w) => !byName.has(w));
if (missing.length) {
  console.error("unknown icons:", missing.join(" "));
  process.exit(1);
}
const names = [...new Set(wanted.map((w) => byName.get(w)))].sort();

const constructor = (n) => {
  const c = n.charAt(0).toUpperCase() + n.slice(1).replaceAll("-", "_");
  return /^[0-9]/.test(c) ? "I" + c : c;
};

const shapes = (name) => {
  const svg = readFileSync(svgPath(name), "utf8");
  const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
  const out = [];
  for (const m of body.matchAll(/<(\w+)([^>]*?)\/?>/g)) {
    const attrs = [...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]);
    out.push([m[1], attrs]);
  }
  return out;
};

const q = JSON.stringify; // OCaml accepts JSON's escapes for these strings
const ml = [];
ml.push("(* Generated by tools/gen-icons.mjs from Lucide (ISC licence); do not edit. *)");
ml.push("open! Import\n");
ml.push("type t =");
for (const n of names) ml.push(`  | ${constructor(n)}`);
ml.push("[@@deriving enumerate, sexp_of, compare, equal]\n");
ml.push("let name = function");
for (const n of names) ml.push(`  | ${constructor(n)} -> ${q(n)}`);
ml.push(";;\n");
ml.push("let of_name = function");
for (const n of names) ml.push(`  | ${q(n)} -> Some ${constructor(n)}`);
ml.push("  | _ -> None\n;;\n");
ml.push("let shapes = function");
for (const n of names) {
  const s = shapes(n)
    .map(([tag, attrs]) => `(${q(tag)}, [ ${attrs.map(([k, v]) => `${q(k)}, ${q(v)}`).join("; ")} ])`)
    .join("; ");
  ml.push(`  | ${constructor(n)} -> [ ${s} ]`);
}
ml.push(";;\n");
ml.push(`let view ?(attrs = []) ?class_ ?(stroke_width = "2") t =
  Node.create_svg
    "svg"
    ~attrs:
      ([ Attr.create "xmlns" "http://www.w3.org/2000/svg"
       ; Attr.create "width" "24"
       ; Attr.create "height" "24"
       ; Attr.create "viewBox" "0 0 24 24"
       ; Attr.create "fill" "none"
       ; Attr.create "stroke" "currentColor"
       ; Attr.create "stroke-width" stroke_width
       ; Attr.create "stroke-linecap" "round"
       ; Attr.create "stroke-linejoin" "round"
       ; Attr.classes ([ "lucide"; "lucide-" ^ name t ] @ Option.to_list class_)
       ; Attr.create "aria-hidden" "true"
       ]
       @ attrs)
    (List.map (shapes t) ~f:(fun (tag, shape_attrs) ->
       Node.create_svg
         tag
         ~attrs:(List.map shape_attrs ~f:(fun (k, v) -> Attr.create k v))
         []))
;;`);
writeFileSync(join(root, "src/icon.ml"), ml.join("\n") + "\n");

const mli = [];
mli.push("(** Lucide icons (https://lucide.dev, ISC licence), drawn as lucide-react");
mli.push("    draws them: a 24x24 [<svg>] stroked with [currentColor], classes");
mli.push("    [lucide lucide-NAME]. shadcn/ui's components size them with their");
mli.push("    [[&_svg]:size-4] classes. Generated by tools/gen-icons.mjs: the icons");
mli.push("    are those in tools/icons.txt. *)\n");
mli.push("open! Import\n");
mli.push("type t =");
for (const n of names) mli.push(`  | ${constructor(n)}`);
mli.push("[@@deriving enumerate, sexp_of, compare, equal]\n");
mli.push("(** Lucide's name for it: [circle-check]. *)");
mli.push("val name : t -> string\n");
mli.push("val of_name : string -> t option\n");
mli.push("(** The icon. [class_] goes after [lucide lucide-NAME] (e.g. [size-4");
mli.push("    text-muted-foreground]); [stroke_width] is [\"2\"]. *)");
mli.push("val view : ?attrs:Attr.t list -> ?class_:string -> ?stroke_width:string -> t -> Node.t");
writeFileSync(join(root, "src/icon.mli"), mli.join("\n") + "\n");
console.log(`${names.length} icons`);
