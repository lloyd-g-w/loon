// node tools/gen-themes.mjs: writes docs/lib/create/create_themes.ml (and
// create_styles.ml, create_shuffle.ml), the
// themes of shadcn/ui's /create customiser (apps/v4/registry/themes.ts: the
// base colours and the accent themes, with their light and dark CSS
// variables), from a checkout of github.com/shadcn-ui/ui ($SHADCN_DIR,
// default ~/src/shadcn-ui).
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const shadcn = process.env.SHADCN_DIR ?? join(homedir(), "src/shadcn-ui");
const src = readFileSync(join(shadcn, "apps/v4/registry/themes.ts"), "utf8");

// The file is one array literal with TypeScript around it.
const start = src.indexOf("[", src.indexOf("export const THEMES"));
const end = src.indexOf("] as const");
const themes = new Function(`return ${src.slice(start, end + 1)}`)();

const str = (s) => JSON.stringify(s);
const vars = (o) =>
  "[ " + Object.entries(o ?? {}).map(([k, v]) => `${str(k)}, ${str(v)}`).join("\n        ; ") + "\n        ]";

let ml = `(* Generated by tools/gen-themes.mjs from shadcn/ui's
   apps/v4/registry/themes.ts: do not edit. *)

let all : Create_theme.t list =
  [ `;
ml += themes
  .map(
    (t) => `{ name = ${str(t.name)}
    ; title = ${str(t.title)}
    ; light =
        ${vars(t.cssVars?.light)}
    ; dark =
        ${vars(t.cssVars?.dark)}
    }`,
  )
  .join("\n  ; ");
ml += "\n  ]\n;;\n";

writeFileSync(join(root, "docs/lib/create/create_themes.ml"), ml);
writeFileSync(
  join(root, "docs/lib/create/create_themes.mli"),
  `(* Generated by tools/gen-themes.mjs: do not edit. *)

(** shadcn's [THEMES], in its order: the base colours, then the accents. *)
val all : Create_theme.t list
`,
);

// The styles (apps/v4/registry/styles.tsx): name, title, description and
// icon, its JSX written as SVG markup.
const stylesSrc = readFileSync(join(shadcn, "apps/v4/registry/styles.tsx"), "utf8");
const jsxToSvg = (jsx) =>
  jsx
    .replace(/\s+/g, " ")
    .replace(/ stroke([A-Z])([a-z]+)=/g, (_, b, c) => ` stroke-${b.toLowerCase()}${c}=`)
    .replace("<svg ", '<svg class="size-4" ')
    .replace(/ width="\d+"| height="\d+"/g, "")
    .replace(/ ?> ?</g, "><")
    .trim();
const styles = [];
for (const m of stylesSrc.matchAll(
  /name: "([^"]+)",\s*title: "([^"]+)",\s*description: "([^"]+)",\s*icon: \(\s*(<svg[\s\S]*?<\/svg>)/g,
))
  styles.push({ name: m[1], title: m[2], description: m[3], icon: jsxToSvg(m[4]) });
writeFileSync(
  join(root, "docs/lib/create/create_styles.ml"),
  `(* Generated by tools/gen-themes.mjs from shadcn/ui's
   apps/v4/registry/styles.tsx: do not edit. *)

let all : Create_style.t list =
  [ ${styles
    .map(
      (s) => `{ name = ${str(s.name)}
    ; title = ${str(s.title)}
    ; description = ${str(s.description)}
    ; icon = ${str(s.icon)}
    }`,
    )
    .join("\n  ; ")}
  ]
;;
`,
);
writeFileSync(
  join(root, "docs/lib/create/create_styles.mli"),
  `(* Generated by tools/gen-themes.mjs: do not edit. *)

(** shadcn's [STYLES], in its order. *)
val all : Create_style.t list
`,
);

// The Shuffle button's presets ((create)/lib/shuffle-presets.ts).
const shuffleSrc = readFileSync(
  join(shadcn, "apps/v4/app/(app)/(create)/lib/shuffle-presets.ts"),
  "utf8",
);
const shuffle = [...shuffleSrc.matchAll(/"(b[0-9A-Za-z]+)"/g)].map((m) => m[1]);
writeFileSync(
  join(root, "docs/lib/create/create_shuffle.ml"),
  `(* Generated by tools/gen-themes.mjs from shadcn/ui's
   apps/v4/app/(app)/(create)/lib/shuffle-presets.ts: do not edit. *)

let presets =
  [ ${shuffle.map(str).join("\n  ; ")}
  ]
;;
`,
);
writeFileSync(
  join(root, "docs/lib/create/create_shuffle.mli"),
  `(* Generated by tools/gen-themes.mjs: do not edit. *)

(** shadcn's [SHUFFLE_PRESETS]: the curated codes Shuffle picks from. *)
val presets : string list
`,
);
console.log(`${themes.length} themes, ${styles.length} styles, ${shuffle.length} shuffle presets`);
