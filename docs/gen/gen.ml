(* gen.exe pages|sources FILE...

   An example in a page's source is the text between a line starting with
   "(*$ Title" (its comment may go on over several lines, as the example's
   description) and a line "(*$*)".
   [sources] prints a module mapping (page, title) to that text; [pages]
   prints the list of the files' [page] values. *)

open! Core

let module_name file =
  Filename.basename file |> Filename.chop_extension |> String.capitalize
;;

let page_slug file =
  Filename.basename file |> Filename.chop_extension |> String.chop_suffix_exn ~suffix:"_page"
;;

let strip_indent lines =
  let indent line =
    if String.is_empty (String.strip line)
    then None
    else Some (String.length line - String.length (String.lstrip line))
  in
  let min_indent =
    List.filter_map lines ~f:indent |> List.min_elt ~compare |> Option.value ~default:0
  in
  List.map lines ~f:(fun line ->
    if String.length line >= min_indent then String.drop_prefix line min_indent else "")
;;

let trim_blank lines =
  let drop l = List.drop_while l ~f:(fun s -> String.is_empty (String.strip s)) in
  drop lines |> List.rev |> drop |> List.rev
;;

let examples file =
  let lines = In_channel.read_lines file in
  let rec outside acc = function
    | [] -> List.rev acc
    | line :: rest ->
      (match String.chop_prefix (String.lstrip line) ~prefix:"(*$ " with
       | None -> outside acc rest
       | Some first ->
         (* the opening comment: its first line is the title, the rest (up to
            "*)") the description *)
         let rec comment acc line rest =
           match String.substr_index line ~pattern:"*)" with
           | Some i -> List.rev (String.prefix line i :: acc), rest
           | None ->
             (match rest with
              | [] -> List.rev (line :: acc), []
              | l :: rest -> comment (line :: acc) l rest)
         in
         let comment_lines, rest = comment [] first rest in
         let title, description =
           match comment_lines with
           | [] -> "", ""
           | title :: more ->
             ( String.strip title
             , List.map more ~f:String.strip
               |> List.filter ~f:(fun s -> not (String.is_empty s))
               |> String.concat ~sep:" " )
         in
         let body, rest =
           List.split_while rest ~f:(fun l -> not (String.equal (String.strip l) "(*$*)"))
         in
         let rest = List.drop rest 1 in
         outside
           (( title
            , description
            , body |> trim_blank |> strip_indent |> String.concat ~sep:"\n" )
            :: acc)
           rest)
  in
  outside [] lines
;;

let () =
  match Sys.get_argv () |> Array.to_list with
  | _ :: "pages" :: files ->
    let files = List.sort files ~compare:String.compare in
    print_endline "(* Generated by docs/gen from pages/*_page.ml. *)";
    print_endline "let all = [";
    List.iter files ~f:(fun f -> printf "  %s.page;\n" (module_name f));
    print_endline "]"
  | _ :: "sources" :: files ->
    let all =
      List.concat_map (List.sort files ~compare:String.compare) ~f:(fun f ->
        List.map (examples f) ~f:(fun e -> page_slug f, e))
    in
    print_endline "(* Generated by docs/gen from pages/*_page.ml. *)";
    print_endline "let find ~page ~title = match page, title with";
    List.iter all ~f:(fun (page, (title, _, body)) ->
      printf "  | %S, %S -> Some {loon_src|%s|loon_src}\n" page title body);
    print_endline "  | _ -> None";
    print_endline "";
    print_endline "let description ~page ~title = match page, title with";
    List.iter all ~f:(fun (page, (title, description, _)) ->
      if not (String.is_empty description)
      then printf "  | %S, %S -> Some %S\n" page title description);
    print_endline "  | _ -> None"
  | _ ->
    eprintf "usage: gen.exe pages|sources FILE...\n";
    exit 2
;;
